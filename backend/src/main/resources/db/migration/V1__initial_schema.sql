CREATE SEQUENCE IF NOT EXISTS resource_id_seq START WITH 1000;
CREATE SEQUENCE IF NOT EXISTS physical_item_id_seq START WITH 10000;
CREATE SEQUENCE IF NOT EXISTS digital_item_id_seq START WITH 1000;

-- -------------------------------------------------------------------------
-- 1. Catalog & Items
-- -------------------------------------------------------------------------
CREATE TABLE resource (
    id BIGINT PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    authors VARCHAR(255) NOT NULL,
    description TEXT,
    category VARCHAR(100),
    isbn VARCHAR(255),
    cover_image_url TEXT,
    metadata_source VARCHAR(32) NOT NULL DEFAULT 'MANUAL',
    external_source_id VARCHAR(255),
    CONSTRAINT uq_resource_isbn UNIQUE (isbn),
    CONSTRAINT chk_resource_metadata_source CHECK (metadata_source IN ('MANUAL', 'GOOGLE_BOOKS'))
);

CREATE TABLE physical_item (
    id BIGINT PRIMARY KEY,
    resource_id BIGINT NOT NULL,
    barcode VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    inventory_status VARCHAR(32) NOT NULL,
    circulation_status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_physical_resource
        FOREIGN KEY (resource_id)
            REFERENCES resource(id)
            ON DELETE CASCADE,
    CONSTRAINT uq_physical_item_barcode UNIQUE (barcode),
    CONSTRAINT chk_physical_item_inventory_status
        CHECK (inventory_status IN ('ACTIVE', 'LOST', 'DAMAGED', 'WITHDRAWN')),
    CONSTRAINT chk_physical_item_circulation_status
        CHECK (circulation_status IN ('AVAILABLE', 'RESERVED', 'BORROWED'))
);

CREATE INDEX idx_physical_item_allocation
    ON physical_item (resource_id, inventory_status, circulation_status, id);

CREATE TABLE digital_item (
    id BIGINT PRIMARY KEY,
    resource_id BIGINT NOT NULL UNIQUE,
    preview_content_key VARCHAR(512),
    full_content_key VARCHAR(512),
    CONSTRAINT fk_digital_resource
        FOREIGN KEY (resource_id)
            REFERENCES resource(id)
            ON DELETE CASCADE
);

-- -------------------------------------------------------------------------
-- 2. Accounts
-- -------------------------------------------------------------------------
CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(255),
    role VARCHAR(32) NOT NULL,
    account_status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    membership_eligible BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT chk_account_role
        CHECK (role IN ('READER', 'LIBRARIAN')),
    CONSTRAINT chk_account_status
        CHECK (account_status IN ('ACTIVE', 'DISABLED'))
);

-- -------------------------------------------------------------------------
-- 3. Circulation (Requests & Borrowings)
-- -------------------------------------------------------------------------
CREATE TABLE borrow_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id BIGINT NOT NULL,
    resource_id BIGINT NOT NULL,
    physical_item_id BIGINT,
    status VARCHAR(32) NOT NULL,
    requested_at TIMESTAMP NOT NULL,
    status_updated_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP,
    prepared_at TIMESTAMP,
    prepared_by BIGINT,
    rejected_at TIMESTAMP,
    rejected_by BIGINT,
    rejection_reason VARCHAR(500),
    fulfilled_at TIMESTAMP,
    fulfilled_by BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_borrow_request_reader
        FOREIGN KEY (reader_id)
            REFERENCES accounts(id),
    CONSTRAINT fk_borrow_request_resource
        FOREIGN KEY (resource_id)
            REFERENCES resource(id),
    CONSTRAINT fk_borrow_request_item
        FOREIGN KEY (physical_item_id)
            REFERENCES physical_item(id),
    CONSTRAINT fk_borrow_request_prepared_by
        FOREIGN KEY (prepared_by)
            REFERENCES accounts(id),
    CONSTRAINT fk_borrow_request_rejected_by
        FOREIGN KEY (rejected_by)
            REFERENCES accounts(id),
    CONSTRAINT fk_borrow_request_fulfilled_by
        FOREIGN KEY (fulfilled_by)
            REFERENCES accounts(id),
    CONSTRAINT chk_borrow_request_status
        CHECK (status IN (
            'REQUESTED',
            'READY_FOR_PICKUP',
            'FULFILLED',
            'CANCELLED',
            'REJECTED',
            'EXPIRED'
        ))
);

CREATE UNIQUE INDEX uq_active_request_physical_item
    ON borrow_request (physical_item_id)
    WHERE status IN ('REQUESTED', 'READY_FOR_PICKUP');

CREATE UNIQUE INDEX uq_active_request_reader_resource
    ON borrow_request (reader_id, resource_id)
    WHERE status IN ('REQUESTED', 'READY_FOR_PICKUP');

CREATE INDEX idx_borrow_request_reader_active
    ON borrow_request (reader_id, status, requested_at, id);

CREATE INDEX idx_borrow_request_reader_outcomes
    ON borrow_request (reader_id, status_updated_at, id);

CREATE INDEX idx_borrow_request_expiration
    ON borrow_request (expires_at, id)
    WHERE status IN ('REQUESTED', 'READY_FOR_PICKUP');

CREATE TABLE borrowing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    physical_item_id BIGINT NOT NULL,
    reader_id BIGINT NOT NULL,
    borrow_request_id BIGINT NOT NULL UNIQUE,
    borrowed_at TIMESTAMP NOT NULL,
    due_at TIMESTAMP NOT NULL,
    returned_at TIMESTAMP,
    CONSTRAINT fk_borrowing_physical
        FOREIGN KEY (physical_item_id)
            REFERENCES physical_item(id),
    CONSTRAINT fk_borrowing_reader
        FOREIGN KEY (reader_id)
            REFERENCES accounts(id),
    CONSTRAINT fk_borrowing_request
        FOREIGN KEY (borrow_request_id)
            REFERENCES borrow_request(id),
    CONSTRAINT chk_borrowing_due_after_borrowed
        CHECK (due_at > borrowed_at),
    CONSTRAINT chk_borrowing_returned_after_borrowed
        CHECK (returned_at IS NULL OR returned_at >= borrowed_at)
);

CREATE UNIQUE INDEX uq_active_borrowing_physical_item
    ON borrowing (physical_item_id)
    WHERE returned_at IS NULL;

CREATE INDEX idx_borrowing_reader_active_due
    ON borrowing (reader_id, due_at, borrowed_at, id)
    WHERE returned_at IS NULL;

CREATE INDEX idx_borrowing_active_due
    ON borrowing (due_at, borrowed_at, id)
    WHERE returned_at IS NULL;

-- -------------------------------------------------------------------------
-- 4. Membership & Payments
-- -------------------------------------------------------------------------
CREATE TABLE membership_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    duration_months INT NOT NULL,
    price_amount NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    monthly_borrow_quota INT,
    active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE payment_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    plan_id BIGINT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    provider_txn_ref VARCHAR(255) UNIQUE,
    provider_transaction_no VARCHAR(255),
    provider_response_code VARCHAR(50),
    CONSTRAINT fk_payment_account FOREIGN KEY (account_id) REFERENCES accounts(id),
    CONSTRAINT fk_payment_plan FOREIGN KEY (plan_id) REFERENCES membership_plan(id),
    CONSTRAINT chk_payment_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED'))
);

CREATE TABLE membership_subscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    plan_id BIGINT NOT NULL,
    payment_transaction_id BIGINT NOT NULL UNIQUE,
    starts_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_sub_account FOREIGN KEY (account_id) REFERENCES accounts(id),
    CONSTRAINT fk_sub_plan FOREIGN KEY (plan_id) REFERENCES membership_plan(id),
    CONSTRAINT fk_sub_payment FOREIGN KEY (payment_transaction_id) REFERENCES payment_transaction(id),
    CONSTRAINT chk_expires_after_starts CHECK (expires_at > starts_at)
);
